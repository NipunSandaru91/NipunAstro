export function buildPersonalTopicReading(input: {
  topic: PredictionTopic;
  level: EvidenceStrength;
  anchors: PersonalReadingAnchor[];
}): PersonalTopicReading {
  const anchors = input.anchors;
  const strengths = [...new Set(anchors.flatMap((anchor) => anchor.supporting))].slice(0, 4);
  const cautions = [...new Set(anchors.flatMap((anchor) => anchor.contradicting))].slice(0, 4);

  return {
    outcome: OUTCOMES[input.topic][input.level],
    anchors: anchors.map((anchor) => ({
      ...anchor,
      resultChannel: DESTINATION_OUTCOMES[anchor.targetBhava],
    })),
    strengths,
    cautions,
  };
}

